from __future__ import annotations
from pathlib import Path
from typing import Protocol, Sequence
from .schemas import AnswerRequest, AnswerResponse, DiscoveredFile, RetrievedChunk, SourceChunk, WebSource

class SourceScanner(Protocol):
    def scan(self, root: Path) -> list[DiscoveredFile]: ...

class DocumentIngestor(Protocol):
    def ingest(self, file: DiscoveredFile, *, resume: bool = True) -> list[SourceChunk]: ...

class Embedder(Protocol):
    @property
    def dimension(self) -> int: ...
    def embed_documents(self, texts: Sequence[str]) -> list[list[float]]: ...
    def embed_query(self, text: str) -> list[float]: ...

class NotesRetriever(Protocol):
    def retrieve(self, question: str, *, subject: str | None = None, top_k: int = 5) -> list[RetrievedChunk]: ...

class WebSearcher(Protocol):
    def search(self, query: str, *, max_results: int = 5) -> list[WebSource]: ...

class AnswerGenerator(Protocol):
    def generate(self, request: AnswerRequest, notes: Sequence[RetrievedChunk], web: Sequence[WebSource]) -> AnswerResponse: ...
